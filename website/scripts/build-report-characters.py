"""Collect public interface characters only; private paper text is added in memory at export."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]/'web_assets'
chars=set(chr(c) for c in range(32,127))
for p in root.glob('*.js'):
 if p.name!='report-characters.js':chars.update(p.read_text())
(root/'report-characters.js').write_text('// Generated by scripts/build-report-characters.py from public UI modules.\nexport const REPORT_CHARACTERS='+json.dumps(''.join(sorted(chars)),ensure_ascii=False)+';\n')
print('Public interface characters:',len(chars))
